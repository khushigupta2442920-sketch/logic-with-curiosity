// START MIND TRAP GAME
// ============================================

export function startMindTrap() {

    const gameContent =
        document.getElementById("gameContent");

    if (!gameContent) return;

    let difficulty = "easy";
    let currentQuestion = 0;
    let score = 0;
    let answered = false;


    function render() {

        const questions =
            mindQuestions[difficulty];

        const question =
            questions[currentQuestion];


        // GAME COMPLETE

        if (!question) {

            gameContent.innerHTML = `

                <div class="result-card">

                    <h2>🧠 Mind Trap Complete!</h2>

                    <p>Tumhara Score</p>

                    <h1>
                        ${score} / ${questions.length}
                    </h1>

                    <button id="mindTrapAgain">
                        🔄 Dobara Khelo
                    </button>

                </div>

            `;

            document
                .getElementById("mindTrapAgain")
                .onclick = () => {

                    currentQuestion = 0;
                    score = 0;
                    answered = false;

                    render();
                };

            return;
        }


        gameContent.innerHTML = `

            <div class="mind-trap-game">

                <div class="funny-levels">

                    <button data-level="easy">
                        🟢 Easy
                    </button>

                    <button data-level="medium">
                        🟡 Medium
                    </button>

                    <button data-level="hard">
                        🔴 Hard
                    </button>

                </div>


                <div class="score-box">
                    🧠 Score: ${score}
                </div>


                <p>
                    Mind Trap
                    ${currentQuestion + 1}
                    / ${questions.length}
                </p>


                <div class="question-card">

                    <h2>${question.q}</h2>

                </div>


                <div
                    id="mindTrapOptions"
                    class="options-container">
                </div>


                <button
                    id="mindTrapHint"
                    class="hint-btn">

                    💡 Hint

                </button>


                <p
                    id="mindTrapHintText"
                    class="hint-text">
                </p>


                <button
                    id="mindTrapNext"
                    class="next-btn hidden">

                    Next ➡️

                </button>

            </div>

        `;


        // LEVELS

        document
            .querySelectorAll(".funny-levels button")
            .forEach(button => {

                button.onclick = () => {

                    difficulty =
                        button.dataset.level;

                    currentQuestion = 0;
                    score = 0;
                    answered = false;

                    render();
                };

            });


        // OPTIONS

        const optionsContainer =
            document.getElementById(
                "mindTrapOptions"
            );


        question.options.forEach(
            (option, index) => {

                const button =
                    document.createElement("button");

                button.className =
                    "option-btn";

                button.textContent =
                    `${String.fromCharCode(65 + index)}. ${option}`;


                button.onclick = () => {

                    if (answered) return;

                    answered = true;

                    const all =
                        document.querySelectorAll(
                            "#mindTrapOptions .option-btn"
                        );


                    all.forEach(btn => {
                        btn.disabled = true;
                    });


                    if (index === question.answer) {

                        button.classList.add("correct");

                        score++;

                    } else {

                        button.classList.add("wrong");

                        all[question.answer]
                            .classList.add("correct");
                    }


                    document
                        .getElementById("mindTrapNext")
                        .classList.remove("hidden");

                };


                optionsContainer
                    .appendChild(button);

            }
        );


        // HINT

        document
            .getElementById("mindTrapHint")
            .onclick = () => {

                document
                    .getElementById("mindTrapHintText")
                    .textContent =
                    "💡 " + question.hint;

            };


        // NEXT

        document
            .getElementById("mindTrapNext")
            .onclick = () => {

                if (!answered) return;

                currentQuestion++;

                answered = false;

                render();
            };

    }


    render();
}
